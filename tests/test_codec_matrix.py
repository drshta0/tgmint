#: source kinds: (name, materialize) — produce the source representation
#: from a canonical SessionData, and read it back via the codec


def _materialize(kind: str, data: SessionData, tmp: str):
    """Return (source_object, reader). source_object is a path or string."""
    if kind == "telethon-sqlite":
        path = os.path.join(tmp, "src-tele.session")
        telethon.write_sqlite(data, path)
        return path, telethon.read_sqlite
    if kind == "telethon-string":
        return telethon.write_string(data), telethon.read_string
    if kind == "pyrogram-sqlite":
        path = os.path.join(tmp, "src-pyro.session")
        pyrogram.write_sqlite(data, path, variant="pyrogram")
        return path, pyrogram.read_sqlite
    if kind == "kurigram-sqlite":
        path = os.path.join(tmp, "src-kuri.session")
        pyrogram.write_sqlite(data, path, variant="kurigram")
        return path, pyrogram.read_sqlite
    if kind == "pyrogram-string":
        return pyrogram.write_string(data), pyrogram.read_string
    if kind == "gramjs-string":
        return gramjs.write_string(data), gramjs.read_string
    if kind == "tdata":
        folder = os.path.join(tmp, "src-tdata")
        _write_synthetic_tdata(folder, data.auth_key, data.user_id)
        from tgmint.codec import tdata

        return folder, tdata.read
    raise ValueError(kind)


#: what each TARGET format preserves of a canonical SessionData (used to
#: build the expected value after write→read)
_TARGETS = {
    "telethon-sqlite": ("dc_id", "auth_key", "server_address", "port"),
    "telethon-string": ("dc_id", "auth_key", "server_address", "port"),
    "pyrogram-sqlite": ("dc_id", "auth_key", "user_id", "is_bot", "test_mode", "api_id"),
    "kurigram-sqlite": (
        "dc_id", "auth_key", "user_id", "is_bot", "test_mode", "api_id",
        "server_address", "port",
    ),
    "pyrogram-string": ("dc_id", "auth_key", "user_id", "is_bot", "test_mode", "api_id"),
    "gramjs-string": ("dc_id", "auth_key", "server_address", "port"),
}

_SOURCES = [
    "telethon-sqlite",
    "telethon-string",
    "pyrogram-sqlite",
    "kurigram-sqlite",
    "pyrogram-string",
    "gramjs-string",
    "tdata",
]


class TestConversionMatrix(unittest.TestCase):
    """Every live from→to cell of the matrix.

    For each (source, target): materialize the source from a canonical
    SessionData, read it back through the codec, write the target, read
    the target back, and compare against exactly the fields the target
    format is documented to preserve (auth_key always byte-equal).
    """

    def _write_target(self, target, data, tmp):
        if target == "telethon-sqlite":
            path = os.path.join(tmp, "out-tele.session")
            telethon.write_sqlite(data, path)
            return telethon.read_sqlite(path)
        if target == "telethon-string":
            return telethon.read_string(telethon.write_string(data))
        if target == "pyrogram-sqlite":
            path = os.path.join(tmp, "out-pyro.session")
            pyrogram.write_sqlite(data, path, variant="pyrogram")
            return pyrogram.read_sqlite(path)
        if target == "kurigram-sqlite":
            path = os.path.join(tmp, "out-kuri.session")
            pyrogram.write_sqlite(data, path, variant="kurigram")
            return pyrogram.read_sqlite(path)
        if target == "pyrogram-string":
            return pyrogram.read_string(pyrogram.write_string(data))
        if target == "gramjs-string":
            return gramjs.read_string(gramjs.write_string(data))
        raise ValueError(target)

    def test_every_supported_cell(self):
        cells = 0
        for source in _SOURCES:
            for target in _TARGETS:
                if source == target:
                    continue  # same-format cells are covered per format above
                with self.subTest(source=source, target=target):
                    key = auth_key()
                    canonical_data = canonical(auth_key=key)
                    with tempfile.TemporaryDirectory() as tmp:
                        if source == "tdata" and not HAVE_QT:
                            self.skipTest("PyQt5 not installed — tdata source skipped")
                        # 1. canonical -> source format -> codec read
                        src_obj, reader = _materialize(source, canonical_data, tmp)
                        loaded = reader(src_obj)
                        # the source may drop identity the target needs
                        # (real converters re-supply it explicitly)
                        to_write = loaded
                        if target in ("pyrogram-sqlite", "kurigram-sqlite", "pyrogram-string"):
                            if loaded.user_id is None:
                                to_write = to_write._replace(user_id=canonical_data.user_id)
                            if loaded.api_id is None:
                                to_write = to_write._replace(api_id=canonical_data.api_id)
                        # 2. codec write -> target format -> codec read
                        result = self._write_target(target, to_write, tmp)
                        # 3. compare exactly the preserved fields
                        self.assertEqual(result.auth_key, key)
                        expected = {
                            field: getattr(canonical_data, field)
                            for field in _TARGETS[target]
                        }
                        for field in expected:
                            got = getattr(result, field)
                            want = expected[field]
                            if field in ("user_id", "is_bot") and want is not None:
                                self.assertEqual(got, want)
                            elif field in ("dc_id", "server_address", "port", "test_mode", "api_id"):
                                self.assertEqual(got, want)
                    cells += 1
        # the grid actually exercised what the matrix promises
        self.assertGreaterEqual(cells, 30)


