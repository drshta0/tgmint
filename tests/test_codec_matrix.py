"""Offline tests for tgmint.codec — the conversion matrix.

Honest verification labels (matching the module docstrings):

* **Telethon (SQLite + StringSession v1) — fully verified offline against
  real Telethon 1.43.2.**  Where telethon is importable we assert against
  it as an external oracle: our string writer is byte-identical to
  ``StringSession.save()``, our written ``.session`` files open with
  ``SQLiteSession`` (upgrading schema 7 → 8), telethon-written files
  (schema 8, ``tmp_auth_key`` column) read back here, and the hardcoded
  TELE_VECTOR constant below was generated by real telethon.
* **GramJS — cross-checked against TGConvertor's own semantics only.**
  Vectors are constructed in-test straight from the documented layout
  (``struct`` + ``base64``, never via our own writer), including the two
  Telethon-shaped-body cross-detection guards.
* **Pyrogram / kurigram — self-consistent only.**  No pyrogram-family
  client is installed here, so we can only prove we read back exactly
  what we write (plus the legacy 1.x string vectors constructed from the
  layout).  Do not read more into the green.
* **tdata — verified against synthetic folders written by
  ``tgmint.td.TDesktop.SaveTData``** (skipped when PyQt5 is missing).

All seeds are ``os.urandom(256)``; every test is offline.
"""

