class TestTelethonSqlite(unittest.TestCase):
    def test_round_trip(self):
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            telethon.write_sqlite(data, path)
            restored = telethon.read_sqlite(path)
            self.assertEqual(restored.auth_key, data.auth_key)
            self.assertEqual(
                (restored.dc_id, restored.server_address, restored.port),
                (DC_ID, ADDRESS, 443),
            )
            # user_id is not stored by Telethon's sessions table
            self.assertIsNone(restored.user_id)
            with closing(sqlite3.connect(path)) as db:
                self.assertEqual(db.execute("SELECT version FROM version").fetchone()[0], 7)

    def test_never_overwrites_and_is_private(self):
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            with open(path, "wb") as fp:
                fp.write(b"keep this")
            with self.assertRaises(FileExistsError):
                telethon.write_sqlite(data, path)
            with open(path, "rb") as fp:
                self.assertEqual(fp.read(), b"keep this")
            other = os.path.join(tmp, "new.session")
            telethon.write_sqlite(data, other)
            self.assertEqual(os.stat(other).st_mode & 0o777, 0o600)
            self.assertEqual(os.listdir(tmp).count("new.session"), 1)

    def test_rejects_ambiguous_or_empty_database(self):
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            telethon.write_sqlite(data, path)
            with closing(sqlite3.connect(path)) as db:
                db.execute("INSERT INTO sessions VALUES (3, '1.2.3.4', 443, x'00', NULL)")
                db.commit()
            with self.assertRaises(CodecError):
                telethon.read_sqlite(path)

    def test_tolerates_additive_schema(self):
        # telethon 1.43 writes schema version 8 with an extra tmp_auth_key
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            telethon.write_sqlite(data, path)
            with closing(sqlite3.connect(path)) as db:
                db.execute("ALTER TABLE sessions ADD tmp_auth_key BLOB")
                db.execute("UPDATE sessions SET tmp_auth_key = x'0102'")
                db.commit()
            self.assertEqual(telethon.read_sqlite(path).auth_key, data.auth_key)

    def test_missing_file_raises_not_creates(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "missing.session")
            with self.assertRaises(FileNotFoundError):
                telethon.read_sqlite(path)
            self.assertFalse(os.path.exists(path))

    def test_null_server_address_is_codec_error(self):
        # a NULL endpoint would escape as a raw ValueError from ipaddress
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            telethon.write_sqlite(data, path)
            with closing(sqlite3.connect(path)) as db:
                db.execute("UPDATE sessions SET server_address = NULL")
                db.commit()
            with self.assertRaises(CodecError) as caught:
                telethon.read_sqlite(path)
            self.assertIn("server_address", str(caught.exception))

    def test_null_auth_key_is_codec_error(self):
        # `bytes(None)` would escape as a TypeError
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            telethon.write_sqlite(data, path)
            with closing(sqlite3.connect(path)) as db:
                db.execute("UPDATE sessions SET auth_key = NULL")
                db.commit()
            with self.assertRaises(CodecError) as caught:
                telethon.read_sqlite(path)
            self.assertIn("auth_key", str(caught.exception))

    def test_hostname_row_falls_back_to_datacenter(self):
        # dc_id is authoritative even for a row written by a laxer client
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "t.session")
            telethon.write_sqlite(data, path)
            with closing(sqlite3.connect(path)) as db:
                db.execute("UPDATE sessions SET server_address = 'dc2.telegram.org'")
                db.commit()
            restored = telethon.read_sqlite(path)
            self.assertEqual((restored.server_address, restored.port), (ADDRESS, 443))
            self.assertFalse(restored.test_mode)

    @unittest.skipUnless(HAVE_TELETHON, "telethon not installed — oracle skipped")
    def test_oracle_real_telethon_reads_our_file(self):
        data = canonical()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "out.session")
            telethon.write_sqlite(data, path)
            native = SQLiteSession(path)
            try:
                self.assertEqual(native.auth_key.key, data.auth_key)
                self.assertEqual(
                    (native.dc_id, native.server_address, native.port),
                    (DC_ID, ADDRESS, 443),
                )
            finally:
                native.close()

    @unittest.skipUnless(HAVE_TELETHON, "telethon not installed — oracle skipped")
    def test_oracle_we_read_telethon_written_file(self):
        key = auth_key()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "real.session")
            native = SQLiteSession(path)
            native.set_dc(DC_ID, ADDRESS, 443)
            native.auth_key = AuthKey(key)
            native.save()
            native.close()
            restored = telethon.read_sqlite(path)
            self.assertEqual(restored.auth_key, key)
            self.assertEqual(
                (restored.dc_id, restored.server_address, restored.port),
                (DC_ID, ADDRESS, 443),
            )


