def pyro_string(dc=DC_ID, api_id=API_ID, test=False, key=None, user=USER_ID, bot=False):
    """Build a Pyrogram 2.x string straight from the documented layout."""
    packed = struct.pack(">BI?256sQ?", dc, api_id, test, key or VECTOR_KEY, user, bot)
    return base64.urlsafe_b64encode(packed).decode().rstrip("=")


def pyro_legacy_string(fmt, user):
    """Build a Pyrogram 1.x string straight from the documented layout."""
    packed = struct.pack(fmt, DC_ID, True, VECTOR_KEY, user, True)
    return base64.urlsafe_b64encode(packed).decode().rstrip("=")


def gramjs_string(address=b"149.154.167.51", port=443, dc=DC_ID, key=None):
    """Build a GramJS string straight from the documented layout."""
    raw = (
        struct.pack(">Bh", dc, len(address))
        + address
        + struct.pack(">h", port)
        + (key or VECTOR_KEY)
    )
    return "1" + base64.b64encode(raw).decode()


