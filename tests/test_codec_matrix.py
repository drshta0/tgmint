class TestTelethonString(unittest.TestCase):
    def test_round_trip_ipv4_and_ipv6(self):
        for address, port in (("149.154.167.51", 443), ("2001:67c:4e8:f002::a", 8443)):
            with self.subTest(address=address):
                data = canonical(server_address=address, port=port)
                restored = telethon.read_string(telethon.write_string(data))
                self.assertEqual(restored.auth_key, data.auth_key)
                self.assertEqual(
                    (restored.dc_id, restored.server_address, restored.port),
                    (data.dc_id, restored.server_address, data.port),
                )
                # the v1 string format cannot carry identity
                self.assertIsNone(restored.user_id)
                self.assertIsNone(restored.is_bot)
                self.assertIsNone(restored.api_id)

    def test_documented_vector(self):
        data = telethon.read_string(TELE_VECTOR)
        self.assertEqual((data.dc_id, data.server_address, data.port), (2, "149.154.167.51", 443))
        self.assertEqual(data.auth_key, VECTOR_KEY)
        self.assertFalse(data.test_mode)
        data6 = telethon.read_string(TELE6_VECTOR)
        self.assertEqual((data6.dc_id, data6.server_address, data6.port), (4, "2001:67c:4e8:f004::a", 8443))
        self.assertEqual(data6.auth_key, VECTOR_KEY)

    def test_writer_reproduces_vector(self):
        ours = telethon.write_string(
            SessionData(dc_id=2, auth_key=VECTOR_KEY, server_address="149.154.167.51", port=443)
        )
        self.assertEqual(ours, TELE_VECTOR)

    @unittest.skipUnless(HAVE_TELETHON, "telethon not installed — oracle skipped")
    def test_oracle_real_telethon(self):
        key = auth_key()
        data = canonical(auth_key=key)
        ours = telethon.write_string(data)
        native = StringSession()
        native._dc_id, native._server_address, native._port = 2, ADDRESS, 443
        native._auth_key = AuthKey(key)
        # byte-identical to what real telethon emits (padded urlsafe b64)
        self.assertEqual(ours, native.save())
        # and real telethon accepts our string
        parsed = StringSession(ours)
        self.assertEqual(parsed.auth_key.key, key)
        self.assertEqual((parsed.dc_id, parsed.server_address, parsed.port), (2, ADDRESS, 443))

    def test_reader_accepts_unpadded_body(self):
        # real telethon always pads (and rejects unpadded input itself);
        # our reader is deliberately more forgiving on input
        data = telethon.read_string(TELE_VECTOR.rstrip("="))
        self.assertEqual(data.auth_key, VECTOR_KEY)

    def test_address_defaults_resolved_from_dc(self):
        data = canonical(server_address=None, port=None)
        string = telethon.write_string(data)
        restored = telethon.read_string(string)
        self.assertEqual(restored.server_address, data_center(DC_ID)[0])
        self.assertEqual(restored.port, 443)

    def test_rejects_invalid_strings(self):
        for bad in ("", "2invalid", "1AAAA", "1" + "A" * 800, None, "1" + "A" * 350):
            with self.subTest(bad=bad):
                with self.assertRaises(CodecError):
                    telethon.read_string(bad)

    def test_hostname_falls_back_to_datacenter(self):
        # dc_id is authoritative: a Telethon endpoint packs a *binary* IP, so
        # a hostname (which only the GramJS format can carry) is replaced by
        # the canonical address of the data center the auth key belongs to.
        data = canonical(server_address="dc2.telegram.org")
        restored = telethon.read_string(telethon.write_string(data))
        self.assertEqual((restored.dc_id, restored.server_address, restored.port), (DC_ID, ADDRESS, 443))

    def test_hostname_fallback_respects_test_mode(self):
        data = canonical(server_address="dc2.telegram.org", port=None, test_mode=True)
        restored = telethon.read_string(telethon.write_string(data))
        self.assertEqual((restored.server_address, restored.port), (TEST_DC[DC_ID], 80))
        self.assertTrue(restored.test_mode)

    def test_hostname_fallback_needs_a_known_dc(self):
        # nothing to fall back to: the dc_id has no published address
        with self.assertRaises(CodecError):
            telethon.write_string(canonical(dc_id=7, server_address="dc2.telegram.org"))


