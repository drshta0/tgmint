def _write_synthetic_tdata(folder: str, key: bytes, user_id: int = USER_ID, passcode: str = "") -> None:
    """Create a genuine tdata folder with tgmint.td's own SaveTData
    (same technique as tests/test_tdata_roundtrip.py)."""
    td = TDesktop()
