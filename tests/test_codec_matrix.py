class TestPyrogramString(unittest.TestCase):
    def test_round_trip_current_format(self):
        for test_mode in (False, True):
            for is_bot in (False, True):
                with self.subTest(test_mode=test_mode, is_bot=is_bot):
                    data = canonical(test_mode=test_mode, is_bot=is_bot)
                    restored = pyrogram.read_string(pyrogram.write_string(data))
                    self.assertEqual(restored.auth_key, data.auth_key)
                    self.assertEqual(
                        (restored.dc_id, restored.user_id, restored.api_id),
                        (DC_ID, USER_ID, API_ID),
                    )
                    self.assertIs(restored.test_mode, test_mode)
                    self.assertIs(restored.is_bot, is_bot)
                    # endpoint is not representable in the string format
                    self.assertIsNone(restored.server_address)
                    self.assertIsNone(restored.port)

    def test_documented_vectors(self):
        # current layout, constructed independently of our writer
        data = pyrogram.read_string(pyro_string())
        self.assertEqual(
            (data.dc_id, data.api_id, data.user_id, data.auth_key), (DC_ID, API_ID, USER_ID, VECTOR_KEY)
        )
        self.assertFalse(data.test_mode)
        self.assertFalse(data.is_bot)
        # legacy 1.x layouts (32- and 64-bit user ids, no api_id)
        for fmt, user in ((">B?256sI?", 123456), (">B?256sQ?", 2**40)):
            with self.subTest(fmt=fmt):
                legacy = pyrogram.read_string(pyro_legacy_string(fmt, user))
                self.assertEqual((legacy.dc_id, legacy.user_id, legacy.auth_key), (DC_ID, user, VECTOR_KEY))
                self.assertTrue(legacy.test_mode)
                self.assertTrue(legacy.is_bot)
                self.assertIsNone(legacy.api_id)

    def test_rejects_invalid_strings(self):
        for bad in ("", "!!!", "AAAA", "A" * 800, None):
            with self.subTest(bad=bad):
                with self.assertRaises(CodecError):
                    pyrogram.read_string(bad)

    def test_rejects_non_boolean_fields(self):
        raw = bytearray(base64.urlsafe_b64decode(pyro_string() + "=="))
        for offset in (5, len(raw) - 1):
            with self.subTest(offset=offset):
                raw[offset] = 2
                value = base64.urlsafe_b64encode(bytes(raw)).decode().rstrip("=")
                with self.assertRaises(CodecError):
                    pyrogram.read_string(value)
                raw[offset] = 1 if offset == 5 else 0

    def test_write_requires_identity(self):
        with self.assertRaises(CodecError):
            pyrogram.write_string(canonical(user_id=None))
        with self.assertRaises(CodecError):
            pyrogram.write_string(canonical(api_id=None))


